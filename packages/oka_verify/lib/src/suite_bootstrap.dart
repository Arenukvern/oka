/// Bootstrap source generation for the precompiled-kernel contract
/// (ADR-0048). This is what `build_test`'s boot kernel does, done
/// inline: a tiny generated main that hands the suite's `main` to
/// test_core's VM bootstrap so `dart test --precompiled` can spawn the
/// suite from a kernel dill with no CFE pass.
library;

/// The version of the generated bootstrap contract. Bump it when the shape
/// of the generated entry point changes: the version is part of every
/// suite cache key, so a bump invalidates every cached kernel at once.
const String bootstrapContractVersion = '1';

/// The bootstrap source for one suite. [bootDir] is where the generated
/// file will live; the suite import is computed relative to it.
String suiteBootstrapSource({
  required String suitePath,
  required String bootDir,
}) {
  final relImport = relativeImport(suitePath, bootDir);
  return '''
// GENERATED by the oka verify lane (ADR-0048) — do not edit.
import 'dart:isolate';

import 'package:test_core/src/bootstrap/vm.dart';

import '$relImport' as suite;

void main(List<String> args, SendPort sendPort) {
  internalBootstrapVmTest(() => suite.main, sendPort);
}
''';
}

/// A file-URI-relative import path from [fromDir] to [targetFile], with
/// forward slashes and a `./` prefix when no upward traversal is needed.
String relativeImport(String targetFile, String fromDir) {
  final target = _segments(targetFile, isDir: false);
  final from = _segments(fromDir, isDir: true);
  var common = 0;
  while (common < target.length - 1 &&
      common < from.length &&
      target[common] == from[common]) {
    common++;
  }
  final up = '../' * (from.length - common);
  final down = target.sublist(common).join('/');
  final rel = '$up$down';
  return up.isEmpty ? './$rel' : rel;
}

List<String> _segments(String path, {required bool isDir}) {
  final uri = Uri.file(path);
  final segments = List<String>.of(uri.pathSegments);
  if (isDir) {
    // A directory uri ends in an empty segment; drop it.
    if (segments.isNotEmpty && segments.last.isEmpty) segments.removeLast();
  } else if (segments.isNotEmpty && segments.last.isEmpty) {
    throw ArgumentError('target must be a file, got directory: $path');
  }
  return segments;
}
