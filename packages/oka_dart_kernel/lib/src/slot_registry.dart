/// The S2 slot-registry generator (ADR-0035 §S2): emits revision-suffixed
/// unit slots plus the registry indirection (`Unit featureUnit => current;`
/// shape) as ordinary Dart source. Call sites bind the generated registry —
/// never a concrete revision — so "applying a patch" to a fully AOT program
/// becomes: load the slot revision in-process, flip the pointer.
///
/// Pure and kernel-free (like `unit_graph.dart`): the emitted source is the
/// authoring seam; the kernel pipeline (`tool/deferredize.dart`) still
/// splits the loading units, and `oka_update`'s slot runtime drives the
/// generated loaders through an authenticated update envelope. The
/// provisions are declared values — the app authors the revision libraries
/// (`units/feature_r1.dart`, `units/feature_r2.dart`, …) as real deferred
/// libraries; slots are pre-provisioned at build time and bounded per
/// process (ADR-0035 Part 2d). Deriving provisions automatically from
/// `tool/patch_units.dart` declarations is a future lane, not this surface.
library;

/// One provisioned revision slot of a [SlotFamily].
class SlotRevision {
  const SlotRevision({
    required this.id,
    required this.importUri,
    required this.member,
  });

  /// The revision suffix (`r1`, `r2`, …). The full slot id is
  /// `<family>_<id>` (e.g. `feature_r2`) — the loading-unit seam the
  /// generator emits and manifests name.
  final String id;

  /// Import URI of the revision's library, relative to the generated
  /// registry file (`units/feature_r2.dart`).
  final String importUri;

  /// The library member all revisions export with [SlotFamily.contractType]
  /// (`feature` for `String feature()`). A tear-off of a function or a read
  /// of a constant — the generated indirection assigns it as a value.
  final String member;
}

/// One patchable unit family with its provisioned revision slots.
class SlotFamily {
  const SlotFamily({
    required this.name,
    required this.contractType,
    required this.revisions,
  });

  /// Unit family name (`feature`) — lower_snake_case; generated
  /// identifiers camel-case it (`featureUnit`, `loadFeatureSlot`).
  final String name;

  /// The stable contract every provisioned revision honors, as a Dart
  /// type expression (`String Function()`). Prototype-grade string (like
  /// the ship lane's declaration fingerprint): it is emitted verbatim as
  /// the indirection's declared type, never type-checked here — the
  /// compile of the generated file is the check.
  final String contractType;

  /// The provisioned revision slots, in load order. Deterministic: the
  /// emission preserves this order.
  final List<SlotRevision> revisions;
}

/// The slot provision a registry is generated from.
class SlotProvision {
  const SlotProvision({required this.families});

  /// Families in emission order.
  final List<SlotFamily> families;
}

/// Thrown when a provision cannot form a valid generated registry.
class SlotRegistryException implements Exception {
  SlotRegistryException(this.message);

  final String message;

  @override
  String toString() => 'SlotRegistryException: $message';
}

/// Camel-cases a family name for generated identifiers: `feature` ->
/// `feature`, `audio_mixer` -> `audioMixer`.
String camelCaseFamily(String name) {
  final parts = name.split('_');
  return parts.first +
      [
        for (final part in parts.skip(1))
          if (part.isNotEmpty) part[0].toUpperCase() + part.substring(1),
      ].join();
}

/// The UpperCamelCase form of a family name (`AudioMixer`), for docs.
String pascalCaseFamily(String name) {
  final lower = camelCaseFamily(name);
  return lower[0].toUpperCase() + lower.substring(1);
}

/// Emits the registry source for [provision]. Byte-stable for equal
/// input — the emitted file is a committed artifact and its content is
/// part of every build fingerprint.
String emitSlotRegistrySource(SlotProvision provision) {
  if (provision.families.isEmpty) {
    throw SlotRegistryException('no slot families declared');
  }
  final buffer = StringBuffer();
  buffer.writeln('// GENERATED by the oka S2 slot-registry generator '
      '(ADR-0035 §S2). Do not edit; regenerate instead.');
  buffer.writeln('// Equal provisions emit equal bytes: the generated file '
      'is fingerprinted like any source.');
  buffer.writeln();

  for (final family in provision.families) {
    _validateFamily(family);
    for (final revision in family.revisions) {
      buffer.writeln("import '${revision.importUri}' deferred as "
          '${_slotPrefix(family.name, revision.id)};');
    }
  }
  for (final family in provision.families) {
    buffer.writeln();
    _emitFamily(buffer, family);
  }
  buffer.writeln();
  _emitException(buffer);
  return buffer.toString();
}

String _slotPrefix(String family, String revision) =>
    'slot_${family}_$revision';

void _emitFamily(StringBuffer buffer, SlotFamily family) {
  final camel = camelCaseFamily(family.name);
  final pascal = pascalCaseFamily(family.name);
  final ids = [for (final r in family.revisions) r.id].join(', ');
  final quotedIds =
      [for (final r in family.revisions) "'${r.id}'"].join(', ');

  buffer
    ..writeln('/// The registry indirection (ADR-0035 §S2): call sites bind '
        '`${camel}Unit`, never')
    ..writeln('/// a concrete revision of `$pascal`. Loading a slot revision '
        'flips it; before the')
    ..writeln('/// first load every read throws with the recovery in the '
        'message.')
    ..writeln('${family.contractType} get ${camel}Unit => _${camel}Loaded ??')
    ..writeln("    (throw StateError('slot `${family.name}` has no loaded "
        "revision — call load${pascal}Slot first'));")
    ..writeln()
    ..writeln('set ${camel}Unit(${family.contractType} value) => '
        '_${camel}Loaded = value;')
    ..writeln()
    ..writeln('${family.contractType}? _${camel}Loaded;')
    ..writeln()
    ..writeln("String _${camel}Revision = '';")
    ..writeln()
    ..writeln('/// The currently loaded revision of `$pascal` '
        "('' until the first load).")
    ..writeln('String get ${camel}Revision => _${camel}Revision;')
    ..writeln()
    ..writeln('/// The provisioned revision slots of `$pascal`, in load order.')
    ..writeln('const List<String> ${camel}SlotRevisions = [$quotedIds];')
    ..writeln()
    ..writeln('/// Loads revision [revision] of `$pascal` in-process and '
        'flips the registry')
    ..writeln('/// pointer. Loading the already-current revision is a '
        'no-op; an unprovisioned')
    ..writeln('/// revision throws [SlotSwapException].')
    ..writeln('Future<void> load${pascal}Slot(String revision) async {')
    ..writeln("  if (_${camel}Revision == revision && revision != '') return;")
    ..writeln('  switch (revision) {');
  for (final revisionSlot in family.revisions) {
    buffer
      ..writeln("    case '${revisionSlot.id}':")
      ..writeln('      await ${_slotPrefix(family.name, revisionSlot.id)}'
          '.loadLibrary();')
      ..writeln('      ${camel}Unit = ${_slotPrefix(family.name, revisionSlot.id)}'
          '.${revisionSlot.member};')
      ..writeln('      break;');
  }
  buffer
    ..writeln('    default:')
    ..writeln("      throw SlotSwapException('slot_revision_unknown',")
    ..writeln("          'slot `${family.name}` has no provisioned revision "
        "`\$revision` (provisioned: $ids)');")
    ..writeln('  }')
    ..writeln('  _${camel}Revision = revision;')
    ..writeln('}');
}

void _emitException(StringBuffer buffer) {
  buffer
    ..writeln('/// The S2 in-process swap failure, thrown by generated '
        'loaders and reused')
    ..writeln("/// by the update runtime's refusal vocabulary "
        '(`slot_revision_unknown`).')
    ..writeln('class SlotSwapException implements Exception {')
    ..writeln('  SlotSwapException(this.code, this.message);')
    ..writeln()
    ..writeln('  final String code;')
    ..writeln()
    ..writeln('  final String message;')
    ..writeln()
    ..writeln('  @override')
    ..writeln(r"  String toString() => '$code: $message';")
    ..writeln('}');
}

final RegExp _familyName = RegExp(r'^[a-z][a-z0-9_]*$');
final RegExp _revisionId = RegExp(r'^[a-z0-9_]+$');
final RegExp _identifier = RegExp(r'^[a-zA-Z_$][a-zA-Z0-9_$]*$');

void _validateFamily(SlotFamily family) {
  if (!_familyName.hasMatch(family.name)) {
    throw SlotRegistryException(
        'family name `${family.name}` must be lower_snake_case');
  }
  final contract = family.contractType;
  if (contract.isEmpty ||
      contract.contains('\n') ||
      contract.contains(';') ||
      contract.contains("'")) {
    throw SlotRegistryException(
        'contract type for `${family.name}` must be a single Dart type '
        'expression without newlines, semicolons or single quotes');
  }
  if (family.revisions.isEmpty) {
    throw SlotRegistryException('family `${family.name}` has no revisions');
  }
  final seen = <String>{};
  for (final revision in family.revisions) {
    if (!_revisionId.hasMatch(revision.id)) {
      throw SlotRegistryException('revision id `${revision.id}` of '
          '`${family.name}` must match [a-z0-9_]+');
    }
    if (!seen.add(revision.id)) {
      throw SlotRegistryException('family `${family.name}` declares revision '
          '`${revision.id}` twice');
    }
    if (revision.importUri.isEmpty ||
        revision.importUri.contains('\n') ||
        revision.importUri.contains("'")) {
      throw SlotRegistryException('import URI of `${family.name}` revision '
          '`${revision.id}` must be a plain relative URI');
    }
    if (!_identifier.hasMatch(revision.member)) {
      throw SlotRegistryException('member `${revision.member}` of '
          '`${family.name}` revision `${revision.id}` is not a Dart '
          'identifier');
    }
  }
}
