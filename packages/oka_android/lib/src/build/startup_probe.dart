/// Startup beacon probe (ADR-0029 D7): answers "did Dart `main()` run?" in
/// a release build with zero app surgery.
///
/// When `FlutterBuild.startupProbe` is set, the assemble and AOT steps
/// compile a **generated wrapper entrypoint** instead of the app's own
/// `main`: the wrapper emits `[oka-beacon] main entered` (visible in logcat
/// as `I flutter`), then calls the real entrypoint and emits
/// `[oka-beacon] main returned` when it completes. The verify ladder's
/// `dart-main` rung greps the device log for the beacon.
///
/// The wrapper is generated into the build dir (never next to app sources),
/// is deterministic for a given entrypoint, and only exists in builds that
/// explicitly opt in — normal release artifacts carry no probe.
library;

import 'dart:io';

import 'package:path/path.dart' as p;

/// Logcat needle the `dart-main` verification rung waits for.
const startupBeaconEnteredNeedle = '[oka-beacon] main entered';
const startupBeaconReturnedNeedle = '[oka-beacon] main returned';

/// Detects the real `main` declaration shape in [entrypointSource].
///
/// Returns `(isAsync, takesArgs)`. Throws [FormatException] when no `main`
/// declaration is found — the probe refuses to guess, because a wrong call
/// shape is a compile error in the generated wrapper.
({bool isAsync, bool takesArgs}) detectMainShape(
  final String entrypointSource,
) {
  final m = RegExp(
    r'(?:Future<[^>]*>|Future|void|Null)\s+main\s*\(',
  ).firstMatch(entrypointSource);
  if (m == null) {
    throw const FormatException(
      'startup probe: no `main` declaration found in entrypoint '
      '(expected `void main()` / `Future<void> main(...)`)',
    );
  }
  final open = m.end - 1;
  var depth = 0;
  var close = -1;
  for (var i = open; i < entrypointSource.length; i++) {
    final c = entrypointSource[i];
    if (c == '(') depth++;
    if (c == ')') {
      depth--;
      if (depth == 0) {
        close = i;
        break;
      }
    }
  }
  final params = close > open
      ? entrypointSource.substring(open + 1, close)
      : '';
  final isAsync = entrypointSource.startsWith('Future', m.start);
  final takesArgs = params.contains('List<String>') ||
      params.contains('List<dynamic>') ||
      params.contains('<String>[]');
  return (isAsync: isAsync, takesArgs: takesArgs);
}

/// Generates the beacon wrapper entrypoint and returns its path.
///
/// Deterministic: same inputs → same file content, so assemble/AOT step
/// caches stay stable across runs. [entrypointPath] is resolved relative to
/// [projectPath] when relative.
String generateStartupBeaconEntrypoint({
  required final String projectPath,
  required final String entrypoint,
  required final String buildDir,
}) {
  final realPath = p.isAbsolute(entrypoint)
      ? entrypoint
      : p.join(projectPath, entrypoint);
  final source = File(realPath).readAsStringSync();
  final shape = detectMainShape(source);
  // Built from raw-string parts: the wrapper must carry literal `$` Dart
  // identifiers, which non-raw strings would interpolate.
  final callPrefix = shape.isAsync ? '  await ' : '  ';
  final callArgs = shape.takesArgs ? r'$args' : '';
  final asyncBridge = shape.isAsync
      ? ''
      : r'  await $async.Future<void>.delayed(Duration.zero);';
  final callLine = StringBuffer()
    ..write(callPrefix)
    ..write(r'$app.main(')
    ..write(callArgs)
    ..write(');');
  final wrapper = <String>[
    "// GENERATED by oka's startup probe (ADR-0029 D7) — do not edit or commit.",
    '// Wraps $entrypoint to emit a device-log beacon the verify ladder reads.',
    r"import 'dart:async' as $async;",
    "import '${Uri.file(realPath)}' as \$app;",
    '',
    r'Future<void> main(final List<String> $args) async {',
    '  // ignore: avoid_print',
    "  print('$startupBeaconEnteredNeedle');",
    if (asyncBridge.isNotEmpty) asyncBridge,
    callLine.toString(),
    '  // ignore: avoid_print',
    "  print('$startupBeaconReturnedNeedle');",
    '}',
    '',
  ].join('\n');
  final outDir = Directory(
    p.join(buildDir, 'probe'),
  );
  outDir.createSync(recursive: true);
  final out = File(p.join(outDir.path, 'beacon_main.dart'));
  final existing = out.existsSync() ? out.readAsStringSync() : null;
  if (existing != wrapper) out.writeAsStringSync(wrapper);
  return out.path;
}
